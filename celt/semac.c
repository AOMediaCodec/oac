{
   switch (order) {
   case 1: return oaci_spfb_mixing_foa;
   case 2: return oaci_spfb_mixing_soa;
   case 3: return oaci_spfb_mixing_toa;
   default: return NULL;
   }
}

const float *oaci_semac_get_demixing_matrix(int order)
{
   switch (order) {
   case 1: return oaci_spfb_demixing_foa;
   case 2: return oaci_spfb_demixing_soa;
   case 3: return oaci_spfb_demixing_toa;
   default: return NULL;
   }
}

/* ========================================================================== */
/* SPFB matrix application                                                    */
/* ========================================================================== */

void oaci_semac_apply_mixing(const float *mixing_matrix,
   const celt_sig *freq_in, celt_sig *freq_out,
   int channels, int num_bins)
{
   int b, c, k;
   for (b = 0; b < channels; b++) {
      for (k = 0; k < num_bins; k++) {
         float sum = 0;
         for (c = 0; c < channels; c++)
            sum += mixing_matrix[b * channels + c] * freq_in[c * num_bins + k];
         freq_out[b * num_bins + k] = sum;
      }
   }
}

void oaci_semac_apply_demixing(const float *demixing_matrix,
   const celt_sig *freq_in, celt_sig *freq_out,
   int channels, int num_bins)
{
   int c, b, k;
   for (c = 0; c < channels; c++) {
      for (k = 0; k < num_bins; k++) {
         float sum = 0;
         for (b = 0; b < channels; b++)
            sum += demixing_matrix[c * channels + b] * freq_in[b * num_bins + k];
         freq_out[c * num_bins + k] = sum;
      }
   }
}

/* ========================================================================== */
/* Spatial energy extraction (encoder side)                                   */
/* ========================================================================== */

void oaci_semac_compute_spatial_energy(const CELTMode *mode,
   const celt_sig *freq, celt_sig *beamFreq,
   celt_ener *spatialBandE, celt_glog *spatialLogE,
   int input_order, int effEnd, int end, int C, int LM, int arch)
{
   int num_beams = oaci_semac_get_channels(input_order);
   int N = mode->shortMdctSize << LM;
   const float *mixing = oaci_semac_get_mixing_matrix(input_order);

   celt_assert(mixing != NULL);

   /* Transform ambisonics -> beams and extract per-beam band energies. */
   oaci_semac_apply_mixing(mixing, freq, beamFreq, C, N);
   oaci_compute_band_energies(mode, beamFreq, spatialBandE, effEnd, num_beams, LM, arch);
   oaci_amp2Log2(mode, effEnd, end, spatialBandE, spatialLogE, num_beams);
}

void oaci_semac_create_transport_channels(const CELTMode *mode,
   const celt_sig *beamFreq, celt_sig *freq,
   const celt_ener *spatialBandE,
   int input_order, int effEnd, int C, int coding_channels,
   int transport_domain, int LM)
{
#ifdef SEMAC_SPATIAL_NORMALIZATION
   int num_beams = oaci_semac_get_channels(input_order);
   int N = mode->shortMdctSize << LM;
   int M = 1 << LM;
   VARDECL(celt_norm, beamNorm);
   SAVE_STACK;

   ALLOC(beamNorm, num_beams * N, celt_norm);

   /* Normalize beams to unit energy per band. */
   oaci_normalise_bands(mode, beamFreq, beamNorm, spatialBandE, effEnd, num_beams, M);

   switch (transport_domain) {
   case SEMAC_DOMAIN_BEAM:
      /* Beam-projection (full order only): the normalized beams ARE the
         transport channels (coding_channels == num_beams == C). */
      OAC_COPY(freq, (const celt_sig *)beamNorm, coding_channels * N);
      break;
   case SEMAC_DOMAIN_SHD:
   default:
      /* SHD: transform normalized beams back to the ambisonics domain. */
      {
         const float *demixing = oaci_semac_get_demixing_matrix(input_order);
         celt_assert(demixing != NULL);
         oaci_semac_apply_demixing(demixing, (const celt_sig *)beamNorm, freq, C, N);
      }
      break;
   }

   RESTORE_STACK;
#else /* !SEMAC_SPATIAL_NORMALIZATION */
   (void)mode; (void)beamFreq; (void)freq; (void)spatialBandE;
   (void)input_order; (void)effEnd; (void)C; (void)coding_channels;
   (void)transport_domain; (void)LM;
#endif /* SEMAC_SPATIAL_NORMALIZATION */
}

/* ========================================================================== */
/* SEMAC reconstruction (decoder side)                                        */
/* ========================================================================== */

void oaci_semac_reconstruct(const CELTMode *mode,
   celt_norm *X, celt_glog *oldBandE,
   const celt_glog *spatialLogE,
   int coding_channels, int output_channels,
   int input_order, int transport_domain,
   int start, int effEnd, int end,
   int LM, int arch)
{
   int i, b, c, k, band_start, band_end;
   int num_beams = oaci_semac_get_channels(input_order);
   int nbEBands = mode->nbEBands;
   int M = 1 << LM;
   int N = mode->shortMdctSize << LM;
   const oac_int16 *eBands = mode->eBands;
   const float *mixing = oaci_semac_get_mixing_matrix(input_order);
   const float *demixing = oaci_semac_get_demixing_matrix(input_order);

   VARDECL(celt_sig, freq);
   VARDECL(celt_sig, beamFreq);
   VARDECL(celt_sig, outFreq);
   VARDECL(celt_ener, outBandE);
   SAVE_STACK;

   celt_assert(mixing != NULL && demixing != NULL);
   celt_assert(output_channels == num_beams);

   ALLOC(freq, output_channels * N, celt_sig);
   ALLOC(beamFreq, num_beams * N, celt_sig);
   ALLOC(outFreq, output_channels * N, celt_sig);
   ALLOC(outBandE, output_channels * nbEBands, celt_ener);

   /* Step 1: Denormalize coded channels to get full MDCT spectrum */
   for (c = 0; c < coding_channels; c++)
      oaci_denormalise_bands(mode, X + c * N, freq + c * N,
         oldBandE + c * nbEBands, start, effEnd, M, 1, 0);

   /* Zero-pad higher-order channels */
   for (c = coding_channels; c < output_channels; c++)
      OAC_CLEAR(freq + c * N, N);

   /* Step 2: Get beam-domain signals from the coded transport channels. */
   switch (transport_domain) {
   case SEMAC_DOMAIN_BEAM:
      /* Beam-projection (full order): the coded channels ARE the beams
         (coding_channels == output_channels == num_beams). */
      OAC_COPY(beamFreq, freq, output_channels * N);
      break;
   case SEMAC_DOMAIN_SHD:
   default:
      /* SHD: apply SPFB mixing, ambisonics -> beams. */
      oaci_semac_apply_mixing(mixing, freq, beamFreq, output_channels, N);
      break;
   }

   /* Step 3: Per-band normalize beams, apply spatial energies, inverse SPFB */
   for (i = start; i < effEnd; i++) {
      band_start = M * eBands[i];
      band_end = M * eBands[i + 1];

      /* Compute per-beam energy for this band */
      for (b = 0; b < num_beams; b++) {
         float sum = 1e-27f;
         for (k = band_start; k < band_end; k++)
            sum += beamFreq[b * N + k] * beamFreq[b * N + k];
         float beamE = (float)sqrt(sum);
         float g = 1.f / (1e-27f + beamE);

         /* Normalize this beam's band coefficients */
         for (k = band_start; k < band_end; k++)
            beamFreq[b * N + k] *= g;

         /* Apply spatial energy: denormalize with the transmitted beam energy.
            Same approach as denormalise_bands: lg = bandLogE + eMeans, g = exp2_db(lg). */
         {
#ifdef FIXED_POINT
            celt_glog lg = ADD32(spatialLogE[i + b * nbEBands],
               SHL32((oac_val32)oaci_eMeans[i], DB_SHIFT - 4));
            oac_val32 spatialGain = celt_exp2_db(lg);
#else
            celt_glog lg = spatialLogE[i + b * nbEBands] + oaci_eMeans[i];
            float spatialGain = celt_exp2_db(MIN32(32.f, lg));
#endif
            for (k = band_start; k < band_end; k++)
               beamFreq[b * N + k] *= spatialGain;
         }
      }

      /* Inverse SPFB for this band */
      for (c = 0; c < output_channels; c++) {
         for (k = band_start; k < band_end; k++) {
            float sum = 0;
            for (b = 0; b < num_beams; b++)
               sum += demixing[c * output_channels + b] * beamFreq[b * N + k];
            outFreq[c * N + k] = sum;
         }
      }
   }

   /* Zero out bands outside [start, effEnd) */
   for (c = 0; c < output_channels; c++) {
      for (k = 0; k < M * eBands[start]; k++)
         outFreq[c * N + k] = 0;
      for (k = M * eBands[effEnd]; k < N; k++)
         outFreq[c * N + k] = 0;
   }

   /* Step 4: Compute output band energies and re-normalize for synthesis */
   oaci_compute_band_energies(mode, outFreq, outBandE, effEnd, output_channels, LM, arch);
   oaci_normalise_bands(mode, outFreq, X, outBandE, effEnd, output_channels, M);

   /* Convert to log-domain band energies for oldBandE */
   oaci_amp2Log2(mode, effEnd, end, outBandE, oldBandE, output_channels);

   RESTORE_STACK;
}
